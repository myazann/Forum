_OPTIMIZED_PATH = Path(__file__).parent / "personas_optimized.json"


def get_cards(variant: str = "v2") -> list[dict]:
    """Persona cards for a variant: v1 (prose baseline), v2 (structured),
    v2opt (optimizer output if present, else v2)."""
    if variant == "v1":
        return [{"id": p["id"], "name": p["name"], "profile": p["profile"]} for p in PERSONAS]
    if variant == "v2opt" and _OPTIMIZED_PATH.exists():
        return json.loads(_OPTIMIZED_PATH.read_text())
    return PERSONAS


def card_text(card: dict) -> str:
    """A persona card rendered for prompts. Degrades gracefully for v1."""
    lines = [f"Name: {card['name']}", f"Background: {card['profile']}"]
    for field, label in (
        ("interests", "What they are trying to secure"),
        ("red_lines", "Red lines — they reject anything that crosses these"),
        ("concessions", "What would genuinely win them over"),
    ):
        if card.get(field):
            lines.append(f"{label}:")
            lines += [f"  - {x}" for x in card[field]]
    if card.get("trust_priors"):
        lines.append(f"Trust priors: {card['trust_priors']}")
    if card.get("voice"):
        lines.append(f"Voice: {card['voice']}")
    return "\n".join(lines)
